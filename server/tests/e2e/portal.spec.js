test('portal filters, pagination, recovery, mobile navigation and access boundaries', async ({ page, browser, app }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const customer = await app.api('/auth/signup', null, { name: 'Mobile Customer', email: 'mobile@test.example', password, confirmPassword: password });
  await login(page, 'mobile@test.example');
  const token = await page.evaluate(() => localStorage.getItem('token'));
  const user = await app.api('/auth/me', token);
  const { product, plan } = await catalog(app, 'Mobile');
  const staffToken = app.accounts.staff.token;
  const ids = [];
  for (let i = 0; i < 13; i++) {
    const sub = await app.api('/subscriptions', staffToken, { customer_id: user.id, plan_id: plan.id, start_date: today(),
      expiry_date: addDays(today(), 90), payment_term_days: 15, lines: [{ product_id: product.id, quantity: 1 }] });
    await app.api(`/subscriptions/${sub.id}/actions`, staffToken, { action: 'quote', quotation_valid_until: addDays(today(), 30) });
    ids.push(sub.id);
  }
  await page.reload();
  await expect(page.locator('.portal-subscription')).toHaveCount(12);
  await page.getByRole('button', { name: 'Next ›', exact: true }).click();
  await expect(page.locator('.portal-subscription')).toHaveCount(1);
  await page.getByLabel('Search', { exact: true }).fill('missing');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No matching subscriptions', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await expect(page.locator('.portal-subscription')).toHaveCount(12);
  await page.getByLabel('Status', { exact: true }).selectOption('CLOSED');
  await expect(page.getByRole('heading', { name: 'No matching subscriptions', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();

  await page.route('**/api/portal/subscriptions?*', route => route.fulfill({ status: 503, json: { error: 'Temporarily unavailable' } }));
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Couldn’t load this page', exact: true })).toBeVisible();
  await expect(page.locator('.portal-subscription')).toHaveCount(0);
  await page.unroute('**/api/portal/subscriptions?*');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await expect(page.locator('.portal-subscription')).toHaveCount(12);

  let release;
  const blocked = new Promise(resolve => { release = resolve; });
  await page.route('**/api/portal/subscriptions?*', async route => {
    if (new URL(route.request().url()).searchParams.get('status') === 'CLOSED') await blocked;
    await route.continue();
  });
  await page.getByLabel('Status', { exact: true }).selectOption('CLOSED');
  await expect(page.getByText('Loading your account…', { exact: false })).toBeVisible();
  await page.getByLabel('Status', { exact: true }).selectOption('QUOTATION');
  await expect(page.locator('.portal-subscription')).toHaveCount(12);
  const slowResponse = page.waitForResponse(response => new URL(response.url()).searchParams.get('status') === 'CLOSED');
  release();
  await slowResponse;
  await page.waitForLoadState('networkidle');
  await expect(page.locator('.portal-subscription')).toHaveCount(12);
  await page.unroute('**/api/portal/subscriptions?*');

  for (const width of [1440, 1024, 768, 390, 375, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}px`).toBe(true);
    if (width === 390) await page.screenshot({ path: testInfo.outputPath('portal-mobile.png'), fullPage: true });
    if (width === 1440) await page.screenshot({ path: testInfo.outputPath('portal-desktop.png'), fullPage: true });
  }
  await page.getByRole('button', { name: 'Open menu', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Close menu', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Open menu', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Open menu', exact: true }).click();
  await page.getByRole('link', { name: /My invoices/ }).click();
  await expect(page.getByRole('heading', { name: 'My invoices', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Open menu', exact: true })).toHaveAttribute('aria-expanded', 'false');
  await page.goto('/portal/subscriptions/' + ids[0]);
  await page.getByRole('button', { name: 'Accept quotation', exact: true }).click();
  await app.api(`/subscriptions/${ids[0]}/actions`, staffToken, { action: 'revise' });
  await page.getByRole('dialog').getByRole('button', { name: 'Accept quotation', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh subscription', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Subscription not found');
  const foreign = await app.api('/auth/signup', null, { name: 'Other Customer', email: 'other@test.example', password, confirmPassword: password });
  const denied = await page.request.get('/api/portal/subscriptions/' + ids[1], { headers: { Authorization: 'Bearer ' + foreign.token } });
  expect(denied.status()).toBe(404);
  await page.goto('/dashboard');
  await expect(page).toHaveURL(/\/portal$/);
  const forbidden = await page.request.get('/api/portal/summary', { headers: { Authorization: 'Bearer ' + staffToken } });
  expect(forbidden.status()).toBe(403);
  const anonymous = await browser.newContext({ baseURL: app.baseURL });
  const anonPage = await anonymous.newPage();
  await anonPage.goto('/portal');
  await expect(anonPage).toHaveURL(/\/login$/);
  await anonymous.close();
  expect(customer.user.role).toBe('CUSTOMER');
  expect(errors).toEqual([]);
});

test('a short final billing period is prorated and overdue balances are visible', async ({ page, app }, testInfo) => {
  const customer = await app.api('/auth/signup', null, { name: 'Proration Customer', email: 'proration@test.example', password, confirmPassword: password });
  const { product, plan } = await catalog(app, 'Proration');
  const token = app.accounts.staff.token;
  const sub = await app.api('/subscriptions', token, { customer_id: customer.user.id, plan_id: plan.id, start_date: addDays(today(), -5),
    expiry_date: addDays(today(), 5), payment_term_days: 0, lines: [{ product_id: product.id, quantity: 1 }] });
  for (const action of ['quote', 'confirm', 'activate']) await app.api(`/subscriptions/${sub.id}/actions`, token,
    { action, ...(action === 'quote' ? { quotation_valid_until: today() } : {}) });
  const invoice = await app.api('/invoices', token, { subscription_id: sub.id });
  await app.pool.query('UPDATE invoices SET invoice_date=$1, due_date=$1 WHERE id=$2', [addDays(today(), -5), invoice.id]);
  await app.api(`/invoices/${invoice.id}/actions`, token, { action: 'confirm' });
  await login(page, customer.user.email);
  await expect(page.locator('.portal-metrics dd').nth(3)).not.toHaveText('₹0.00');
  await page.goto('/portal/invoices/' + invoice.id);
  await expect(page.getByText(/Charges are prorated for 11 of \d+ days/)).toBeVisible();
  await expect(page.locator('.portal-balance')).toContainText('Overdue since');
  const issued = await app.api('/portal/invoices/' + invoice.id, customer.token);
  expect(issued.billable_days).toBe(11);
  expect(issued.total).toBeLessThan(310);
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Invoice overflow at ${width}px`).toBe(true);
  }
  await page.screenshot({ path: testInfo.outputPath('invoice-mobile.png'), fullPage: true });
  await page.goto('/portal/subscriptions/' + sub.id);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/portal/profile');
  await expect(page.getByLabel('Full name', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
